#escape double quotes and single quotes
print("Hello \"Python\"") # Hello "Python"
print('Hello \"Python\"') # Hello "Python"
print('Hello \'Python\'') # Hello 'Python'
print("Hello \'Python\'") # Hello 'Python'
print('Hello "Python"') # Hello "Python"
print("Hello 'Python'") # Hello 'Python'
#print("Hello "Python"") # Hello "Python" will cause an error because of the double quotes in the string
#print('Hello ''Python'') # Hello 'Python' will cause an error because of the single quotes in the string

#escape backslash
print("Path: C:\\Users\\Keets\\Documents\\GitHub\\ai-engineer-journey") # Path: C:\Users\Keets\Documents\GitHub\ai-engineer-journey 

#escape new line
print("Hello Python\nHello AI Engineer") 
# Hello Python
# Hello AI Engineer

#escape tab
print("Hello Python\tHello AI Engineer") # Hello Python	    Hello AI Engineer