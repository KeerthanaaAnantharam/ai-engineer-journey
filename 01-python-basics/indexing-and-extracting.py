#indexing
text = "Python"
print(text[0]) #returns 'P' because indexing starts at 0 and text[0] refers to the first character of the string
print(text[-6]) #returns 'P' because negative indexing starts at -1 and text[-6] refers to the first character of the string
print(text[2]) #returns 't' because text[2] refers to the third character of the string

#extracting
date = "2024-06-15"
print(date[0:4]) #returns '2024' because it extracts characters from index 0 to 3
print(date[5:7]) #returns '06' because it extracts characters from index 5 to 6
print(date[-2:]) #returns '15' because it extracts the last two characters of the string

