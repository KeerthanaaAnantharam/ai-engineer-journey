#we need input() to get inputs from the user and that makes the program interactive. 
# The input() function takes a string as an argument, which is displayed as a prompt to the user. 
# The function then waits for the user to type something and press Enter. 
# The input is returned as a string.

print("Please enter your name:")
name = input()  # Get user input and store it in the variable 'name'
print("Hello,", name)  # Greet the user with their name

name = input("Please enter your name: ")  # Prompt the user for their name
print("Hello,", name)  # Greet the user with their name

name = input("Please enter your name: ")  # Prompt the user for their name
country = "India"
print("Hello,", name, "from", country)  # Greet the user with their name and country