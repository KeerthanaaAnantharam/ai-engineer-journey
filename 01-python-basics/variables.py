#print statements without variables
print("My name is Keets")
print("Keets is learning Python")
print("Keets wants to become a Python developer")

#print statements with variables
name = "Keets"
print("My name is", name)
print(name, "is learning Python")
print(name, "wants to become a Python developer")

#print statement with two variables
name = "Keets"
course = "Python"
print("My name is", name)
print(name, "is learning", course)
print(name, "wants to become a", course, "developer")

